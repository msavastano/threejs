def pck_vals(key):
    ms=re.findall(r'BODY%s\s*=\s*\(([^)]*)\)'%key,pck)
    v=ms[-1].replace('D','e').split()
    return [float(x) for x in v]
def pole(n):
    return {'ra':pck_vals(f'{n}_POLE_RA')[:2],'dec':pck_vals(f'{n}_POLE_DEC')[:2],'w':pck_vals(f'{n}_PM')[:2]}
