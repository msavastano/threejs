def sat(name):
    i=s.find('\n '+name+' \n'); seg=[l.strip() for l in s[i:i+400].splitlines() if l.strip()][1:]
    # id, ephem, frame, epoch, then a,e,w,M,i,node,P,Pw,Pnode, then RA,Dec,tilt
    vals=[]
    for x in seg[4:]:
        try: vals.append(float(x))
        except: break
    keys=['a','e','w','M','i','node','P','Pw','Pnode','poleRA','poleDec','tilt']
    d=dict(zip(keys,vals)); d['frame']=seg[2]; return d
